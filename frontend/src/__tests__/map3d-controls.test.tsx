function findRowByLabel(container: HTMLElement, label: string): HTMLElement {
  const span = [...container.querySelectorAll("span")].find((el) => el.textContent === label);
  if (!span) throw new Error(`Row for "${label}" not found — label text may have changed`);
  const row = span.closest(".relative");
  if (!row) throw new Error(`Row container for "${label}" not found`);
  return row as HTMLElement;
}

describe("Map3DControls representative filters", () => {
  for (const { id, label } of FILTER_LAYERS) {
    it(`expands and snapshots the ${id} filter chips`, async () => {
      seedExpandedPanelState();
      const { container } = render(<Map3DControls {...baseProps} />);
      const row = findRowByLabel(container, label);
      const expandBtn = row.querySelector("button");
      expect(expandBtn).toBeTruthy();
      await act(async () => {
        expandBtn!.click();
      });
      const filterArea = row.querySelector(".pl-5.pb-1\\.5");
      expect(filterArea).toBeTruthy();
      expect(filterArea!.innerHTML).toMatchSnapshot();
    });
  }
});

