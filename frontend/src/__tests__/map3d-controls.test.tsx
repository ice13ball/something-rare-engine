// ── 1. Every layer row ───────────────────────────────────────────────────
//
// 53 of the 58 rows are literal `<LayerRow id="...">` blocks. The remaining
// 5 (reserved-areas, relinquished-areas, apeis, protected-marine-sites, eez)
// are generated by a single `.map(cfg => <LayerRow id={cfg.id} .../>)` over
// an inline array — the one dynamic block in the file (grep for
// `id={cfg.id}` to find it again). Both halves are re-derived from source
// here so the count doesn't drift silently if a literal id is renamed.
function deriveLayerRowIds(): string[] {
  const ids: string[] = [];
  const lines = SOURCE.split("\n");
  for (let i = 0; i < lines.length; i++) {
    if (!lines[i].includes("<LayerRow")) continue;
    const chunk = lines.slice(i, i + 8).join("\n");
    const m = chunk.match(/id="([^"]*)"/);
    if (m) ids.push(m[1]);
  }
  return ids;
}

// The 5 ids behind the .map(cfg => ...) block — read straight out of the
// inline config array literal so this list can't drift from the source
// independently of the array it's describing.
function deriveMappedLayerRowIds(): string[] {
  const m = SOURCE.match(/\(\[\s*\{ id: "reserved-areas",[\s\S]*?\] as \{ id: LayerId/);
  if (!m) return [];
  return [...m[0].matchAll(/id: "([^"]*)"/g)].map((x) => x[1]);
}

const LITERAL_IDS = deriveLayerRowIds();
const MAPPED_IDS = deriveMappedLayerRowIds();
const ALL_LAYER_IDS = [...LITERAL_IDS, ...MAPPED_IDS];

