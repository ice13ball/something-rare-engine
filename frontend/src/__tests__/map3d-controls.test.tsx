function jsonResponse(data: unknown) {
  return { ok: true, status: 200, json: async () => data, text: async () => JSON.stringify(data) };
}

// Map3DControls fires 3 of its own fetches (independent of the meta props),
// each gated on activation state so most test states never trigger them —
// but a couple of the representative-filter and prop-driven snapshots do.
const ROUTES: Array<[RegExp, unknown]> = [
  [/\/v2\/spatial\/offshore-activities\/countries/, [{ sovereign: "Norway", count: 12 }]],
  [/\/v1\/acidification\/meta/, { variables: [], depths: [] }],
  [/\/v1\/chi\/meta/, { variables: [], depths: [] }],
];
const fetchMock = vi.fn(async (url: string) => {
  const hit = ROUTES.find(([re]) => re.test(url));
  if (hit) return jsonResponse(hit[1]);
  return Promise.reject(new Error(`Unmocked fetch in map3d-controls.test.tsx: ${url}`));
});

// jsdom does not implement window.matchMedia — Map3DControls calls it
// synchronously (isMobile()) on every render to decide mobile vs desktop
// layout. Without this stub every render throws "matchMedia is not a
// function" before any assertion runs.
function stubMatchMedia(matchesMobile: boolean) {
  vi.stubGlobal("matchMedia", (query: string) => ({
    matches: query.includes("max-width") ? matchesMobile : false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }));
}

// Panel open/section-expand/subgroup-expand state is all localStorage-backed
// (`abyssal_layers_panel`, `abyssal_subgroups`) so it persists across
// reloads for real users — which means it also leaks across tests unless
// reset. Seed it fully expanded so every row in the component is actually
// mounted and visible to the assertions below, rather than hidden behind a
// collapsed section/subgroup.
function seedExpandedPanelState() {
  localStorage.setItem(
    "abyssal_layers_panel",
    JSON.stringify({ open: true, seaOpen: true, landOpen: true, expandedFilter: null }),
  );
  const allExpanded = Object.fromEntries(SUBGROUP_STORAGE_KEYS.map((k) => [k, true]));
  localStorage.setItem("abyssal_subgroups", JSON.stringify(allExpanded));
}

